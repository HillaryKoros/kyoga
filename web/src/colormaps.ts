export const PALETTE_NAMES = Object.keys(PALETTES);

const toHex = ([r, g, b]: [number, number, number]) =>
  "#" + [r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("");

export function gradientCss(name: string): string {
  const stops = (PALETTES[name] ?? PALETTES.viridis).map(toHex).join(", ");
  return `linear-gradient(to right, ${stops})`;
}

export function paletteHex(name: string): string[] {
  return (PALETTES[name] ?? PALETTES.viridis).map(toHex);
}

// Build a maplibre-cog-protocol URL: cog://<url>#color:[<hex array>],vmin,vmax,c
export function cogTileUrl(absoluteUrl: string, palette: string, vmin: number, vmax: number): string {
  const hex = JSON.stringify(paletteHex(palette));
  return `cog://${absoluteUrl}#color:${hex},${vmin},${vmax},c`;
}
